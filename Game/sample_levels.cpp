// Game/sample_levels.cpp - see sample_levels.h.
#include "Game/sample_levels.h"

#include <array>

namespace Game {

namespace {

constexpr int32 kSamples = 0x3712;

struct Table {
    std::array<uint8, kSamples * 2> bytes{};

    void set(int32 index, uint8 level, uint8 range) noexcept
    {
        if (index >= 0 && index < kSamples)
        {
            bytes[static_cast<std::size_t>(index) * 2] = level;
            bytes[static_cast<std::size_t>(index) * 2 + 1] = range;
        }
    }
    void span(int32 from, int32 to, uint8 level, uint8 range) noexcept
    {
        for (int32 i = from; i < to; ++i)
            set(i, level, range);
    }

    Table() noexcept
    {
        span(0, kSamples, 0x7f, 0x28); // 0x447080
        // 0x4470a0
        span(0x76, 0x88, 0x5a, 10);
        span(0x7a, 0x7c, 0x6e, 10);
        span(0x77, 0x7a, 0x50, 10);
        span(0x7c, 0x83, 0x28, 10);
        set(0x7e, 0x5a, 10);
        span(0x4e, 0x76, 0x19, 0x14); // 0x447130
        // 0x447150
        span(1, 0x4e, 100, 0x3c);
        span(0x26, 0x28, 0x1e, 0x1e);
        // 0x447190
        span(0x88, 0xda, 0x3c, 0x28);
        span(0xd6, 0xd9, 100, 0x1e);
        span(0xb7, 0xcd, 0x7f, 0x32);
        span(0xbf, 0xc1, 100, 0x14);
        span(0xcd, 0xd6, 0x50, 0x14);
        span(0xa6, 0xb7, 0x7f, 0x14);
        span(0x8e, 0x90, 0x32, 10);
        set(0x90, 0x46, 10);
        span(0x91, 0x94, 0x7f, 0x14);
        span(0x94, 0x9e, 0x7f, 0x28);
        span(0x89, 0x8c, 0x32, 0x1e);
        span(0x8c, 0x8e, 100, 0x1e);
        span(0xa3, 0xa6, 100, 10);
        // 0x446ef0
        span(0xde, 0xeb, 0x7f, 0x28);
        set(0x130, 100, 4);
        span(0x124, 0x130, 0x1e, 10);
        span(0x10b, 0x10d, 0x37, 0x1e);
        span(0x114, 0x116, 0x3c, 0xf);
        span(0x116, 0x11d, 0x3c, 0xf);
        set(0xe0, 0x7f, 0x14);
        span(0xe1, 0xe4, 0x7f, 0x32);
        span(0x11d, 0x121, 0x50, 0x14);
        span(0xe4, 0xeb, 0x6e, 0x28);
        span(0x107, 0x109, 100, 10);
        set(0x109, 0x5a, 10);
        span(0xfe, 0x103, 0x6e, 0xf);
        span(0xec, 0x103, 0x7f, 0x28); // 0x447050
        span(0x13b, kSamples, 0x50, 0x28); // 0x4472f0 (from 0x6c2b48 = 0x13b)
        // 0x447320
        set(0x36e9, 0x5a, 0x19);
        set(0x36ea, 0x5a, 0x19);
        set(0x36e6, 0x5a, 0x1e);
        set(0x36e7, 0x5a, 0x1e);
        set(0x36f4, 0x7f, 0x1e);
        set(0x36f5, 0x7f, 0x1e);
        set(0x36ec, 100, 0x37);
        set(0x36ed, 100, 0x37);
        set(0x36ee, 0x3f, 0xc);
        set(0x36f8, 100, 0x1e);
        set(0x36f9, 0x7f, 0x1e);
        set(0x36fa, 100, 0x3c);
        set(0x36fb, 100, 0x3c);
        set(0x36f6, 0x46, 0x1e);
    }
};

} // namespace

SampleLevel sampleLevel(int32 index) noexcept
{
    static const Table table;
    if (index < 0 || index >= kSamples)
        return {};
    return {table.bytes[static_cast<std::size_t>(index) * 2], static_cast<float32>(table.bytes[static_cast<std::size_t>(index) * 2 + 1])};
}

} // namespace Game
