// Picks an index by weight (0x5a9b60 / 0x5a9e30): a draw in [0, sum], the first whose running
// total reaches it.
template <std::size_t N>
std::size_t pickWeighted(const std::array<float32, N>& w, std::mt19937& rng)
{
    float32 sum = 0.0f;
    for (float32 x : w)
        sum += x;
    // 0x493c70: (rand & 0x7ff) / 2047 of the range.
    const float32 r = static_cast<float32>(rng() & 0x7ffu) / 2047.0f * sum;
    float32 run = 0.0f;
    for (std::size_t i = 0; i < N; ++i)
    {
        run += w[i];
        if (r <= run)
            return i;
    }
    return N;
}

bool equalsNoCase(std::string_view a, std::string_view b)
{
    return a.size() == b.size() && std::equal(a.begin(), a.end(), b.begin(), [](char x, char y) {
               return std::tolower(static_cast<unsigned char>(x)) == std::tolower(static_cast<unsigned char>(y));
           });
}

