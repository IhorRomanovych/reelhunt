const MeleeFootwork& meleeFootwork(int32 index, bool hardDifficulty)
{
    if (index < 0 || index >= kMeleeTraitCount)
        index = kDefaultMeleeTraits;
    return kFootwork[hardDifficulty ? 1 : 0][static_cast<std::size_t>(index)];
}

int32 pickFootwork(const MeleeFootwork& footwork, std::mt19937& rng)
{
    const auto& m = footwork.moves;
    const float32 total = m[0] + m[1] + m[2] + m[3];
    if (total <= 0.0f)
        return 3;
    float32 r = std::uniform_real_distribution<float32>(0.0f, total)(rng);
    for (int32 i = 0; i < 3; ++i)
        if ((r -= m[static_cast<std::size_t>(i)]) < 0.0f)
            return i;
    return 3;
}

const MeleeTraits& meleeTraits(int32 index, bool hardDifficulty)
{
    if (index < 0 || index >= kMeleeTraitCount)
        index = kDefaultMeleeTraits;
    if (hardDifficulty && index >= 1 && index <= 12)
        return kHardGangs[index - 1];
    return kNormal[index];
}

