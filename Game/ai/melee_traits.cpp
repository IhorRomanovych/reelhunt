int32 classifyMeleeSituation(const MeleeView& v)
{
    constexpr float32 kClose = 2.5f;     // 0x79c3f0
    constexpr float32 kFacing = 20.0f;   // degrees, 0x79c3f4
    constexpr float32 kReact = 0.11f;    // 0.1 + 0.01 (0x79c3fc, 0x79c400)
    constexpr float32 kMargin = 0.01f;
    constexpr float32 kGuardUp = 0.302f; // its guard action's +0x4c past 0x12e (read as ms)
    const bool inReach = v.distance < v.reach;
    auto idle = [&] {
        if (v.distance < kClose && v.facing < kFacing)
            return 2;
        if (inReach)
            return 1;
        return v.distance < kClose ? 0 : 13;
    };
    if (v.playerBlocking)
        return 3;
    if (v.playerGrabbing)
        return v.distance < kClose && v.facing < kFacing ? 11 : idle();
    if (!v.playerSwinging)
        return idle();
    if (v.swingTime < v.swingLands)
    {
        // His blow is on its way: time to answer it, or (a hard one) at its guard.
        if (!inReach)
            return idle();
        if (v.swingLands - v.swingTime > kReact)
            return 4;
        // His hard blow (combat action 8, early) at it in its guard (its combat action 0x13):
        // 5 with the guard held past 0x12e (ours: 0.3 s), 6 while it is still going up.
        if (!v.swingHard)
            return idle();
        if (!v.selfBlocking)
            return 14;
        return v.selfBlockAge > kGuardUp ? 5 : 6;
    }
    // It has landed: how long until his swing is over (his hard blow's time, as the exe reads).
    if (v.distance >= kClose)
        return idle();
    const float32 rest = v.hardLands - v.swingTime;
    if (rest > v.selfGrabTime + kMargin)
        return 9;
    if (rest > v.selfQuickLands + kMargin)
        return 8;
    if (rest > kReact)
        return 7;
    if (rest < 0.0f && (v.selfBlocking || v.selfHurt))
        return 10;
    return idle();
}

MeleeResponse pickMeleeResponse(const MeleeTraits& t, int32 situation, std::mt19937& rng)
{
    if (situation < 0 || situation > 11)
        return MeleeResponse::Wait;
    const std::array<float32, 6>& w = t.situations[static_cast<std::size_t>(situation)];
    float32 total = 0.0f;
    for (float32 x : w)
        total += x;
    if (total <= 0.0f)
        return MeleeResponse::Wait;
    float32 r = std::uniform_real_distribution<float32>(0.0f, total)(rng);
    for (std::size_t i = 0; i < w.size(); ++i)
        if ((r -= w[i]) < 0.0f)
            return static_cast<MeleeResponse>(i);
    return MeleeResponse::Wait;
}

MeleeResponse chooseMeleeResponse(const MeleeTraits& t, MeleeRepeats& rep, int32 situation, bool noQuick,
                                  bool noHard, bool noGrapple, std::mt19937& rng)
{
    if (situation < 0 || situation > 11)
        return MeleeResponse::Wait;
    std::array<uint8, 4>& c = rep.count;
    auto bump = [](uint8& n) { n = static_cast<uint8>(std::min(255, n + 1)); };
    switch (situation)
    {
    case 3: bump(c[3]); break;
    case 4: bump(c[0]); c[1] = c[2] = c[3] = 0; break;
    case 7: case 8: case 9: bump(c[1]); c[0] = c[2] = c[3] = 0; break;
    case 11: bump(c[2]); c[0] = c[1] = c[3] = 0; break;
    default: break;
    }
    std::array<float32, 6> w = t.situations[static_cast<std::size_t>(situation)];
    enum { kWait, kQuick, kHard, kGrapple, kBlock, kTaunt };
    auto over = [&](int32 k) {
        return static_cast<float32>(static_cast<int32>(c[static_cast<std::size_t>(k)]) - t.repeatLimit[static_cast<std::size_t>(k)]) *
               t.repeatScale[static_cast<std::size_t>(k)];
    };
    // 0x5a9bd0: a ruled-out response gets no weight; otherwise past a repeat limit the record
    // reweights (0x5a9c80 / 0x5a9d00 / 0x5a9d90 / 0x5a9de0; each is gated by the flag of the
    // same position, as in the exe).
    if (noQuick)
        w[kQuick] = 0.0f;
    else if (c[0] > t.repeatLimit[0])
    {
        const float32 f = over(0);
        if (situation == 4)
            w[kBlock] *= f;
        else if (situation == 5)
        {
            w[kQuick] *= t.repeatScale[0];
            w[kHard] *= f;
            w[kGrapple] *= f;
        }
        else if (situation == 6)
            w[kQuick] *= f;
    }
    if (noHard)
        w[kHard] = 0.0f;
    else if (c[1] > t.repeatLimit[1])
    {
        const float32 f = over(1);
        if (situation == 7)
            w[kBlock] *= f;
        else if (situation == 8)
        {
            w[kBlock] *= t.repeatScale[1];
            w[kQuick] *= f;
        }
        else if (situation == 9)
        {
            w[kQuick] *= f;
            w[kBlock] *= t.repeatScale[1];
            w[kGrapple] *= f;
        }
        else if (situation == 10)
        {
            w[kQuick] *= f;
            w[kGrapple] *= f;
        }
    }
    if (noGrapple)
        w[kGrapple] = 0.0f;
    else if (c[2] > t.repeatLimit[2] && situation == 11)
        w[kQuick] *= over(2);
    if (c[3] > t.repeatLimit[3] && situation <= 3)
    {
        const float32 f = over(3);
        w[kGrapple] *= f;
        w[kHard] *= f;
    }
    const std::size_t i = pickWeighted(w, rng);
    return i < 6 ? static_cast<MeleeResponse>(i) : MeleeResponse::Wait;
}

std::vector<bool> chooseMeleeCombo(const MeleeTraits& t, std::mt19937& rng)
{
    // 0x569f40 by combo type: 8 Q, 9 QQ, 10 QH, 11 QQQ, 12 QQH.
    switch (pickWeighted(t.attackTypes, rng))
    {
    case 9: return {false, false};
    case 10: return {false, true};
    case 11: return {false, false, false};
    case 12: return {false, false, true};
    default: return {false};
    }
}

